-- IT Asset Management System — initial schema
--
-- Four tables are intentional:
--   asset_types     configurable list managed in Settings
--   assets          the asset register itself
--   documents       one row per generated PDF (individual asset or register export)
--   document_items  the exact asset set inside a register export
--
-- document_items exists because requirement E demands that the exported rows match the
-- selected records, and a PDF is opaque: without this table there is no way to answer
-- "which assets did document X contain?" after the fact.

create extension if not exists "pg_trgm" with schema extensions;

-- ---------------------------------------------------------------------------
-- asset_types
-- ---------------------------------------------------------------------------
create table public.asset_types (
  id         bigint generated by default as identity primary key,
  code       text        not null unique,
  name       text        not null unique,
  sort_order integer     not null default 0,
  is_active  boolean     not null default true,
  created_at timestamptz not null default now(),
  constraint asset_types_code_format check (code ~ '^[A-Z0-9_]{2,16}$'),
  constraint asset_types_name_not_blank check (btrim(name) <> '')
);

comment on table public.asset_types is 'Configurable IT asset types (PC, MT, CT, Printer, UPS, ...)';

-- ---------------------------------------------------------------------------
-- assets
-- ---------------------------------------------------------------------------
create table public.assets (
  id                 uuid        primary key default gen_random_uuid(),
  asset_code         text        not null,
  asset_name         text        not null,
  asset_type_id      bigint      not null references public.asset_types (id) on delete restrict,
  brand              text,
  model              text,
  serial_number      text,
  responsible_person text,
  department         text,
  location           text,
  acquisition_date   date,
  status             text        not null default 'active',
  notes              text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  created_by         uuid        references auth.users (id) on delete set null,
  updated_by         uuid        references auth.users (id) on delete set null,
  constraint assets_code_format check (asset_code ~ '^[A-Z0-9][A-Z0-9._/-]{2,31}$'),
  constraint assets_name_not_blank check (btrim(asset_name) <> ''),
  constraint assets_status_valid check (status in ('active', 'in_repair', 'retired', 'disposed', 'lost'))
);

-- Asset codes are the business key and are stored upper-case (the app normalises them).
create unique index assets_asset_code_key on public.assets (asset_code);

-- A serial number is optional, but a non-empty one must be unique.
create unique index assets_serial_number_key on public.assets (serial_number)
  where serial_number is not null and btrim(serial_number) <> '';

create index assets_asset_type_id_idx on public.assets (asset_type_id);
create index assets_status_idx on public.assets (status);
create index assets_department_idx on public.assets (department);
create index assets_location_idx on public.assets (location);
create index assets_acquisition_date_idx on public.assets (acquisition_date desc);

-- Substring search (ILIKE %term%) on the three searchable columns.
create index assets_asset_code_trgm_idx on public.assets using gin (asset_code gin_trgm_ops);
create index assets_asset_name_trgm_idx on public.assets using gin (asset_name gin_trgm_ops);
create index assets_serial_number_trgm_idx on public.assets using gin (serial_number gin_trgm_ops);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger assets_set_updated_at
  before update on public.assets
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- documents
-- ---------------------------------------------------------------------------
create table public.documents (
  id                uuid        primary key default gen_random_uuid(),
  document_number   text        not null,
  document_type     text        not null,
  asset_id          uuid        references public.assets (id) on delete restrict,
  revision          integer     not null default 1,
  storage_path      text,
  file_size_bytes   bigint,
  generation_status text        not null default 'pending',
  error_message     text,
  created_at        timestamptz not null default now(),
  completed_at      timestamptz,
  created_by        uuid        references auth.users (id) on delete set null,
  constraint documents_number_revision_key unique (document_number, revision),
  constraint documents_type_valid check (document_type in ('asset', 'register')),
  constraint documents_revision_positive check (revision > 0),
  constraint documents_status_valid
    check (generation_status in ('pending', 'generating', 'ready', 'failed')),
  constraint documents_asset_required
    check (document_type <> 'asset' or asset_id is not null),
  constraint documents_ready_has_file
    check (generation_status <> 'ready' or (storage_path is not null and file_size_bytes is not null))
);

create index documents_asset_id_idx on public.documents (asset_id);
create index documents_created_at_idx on public.documents (created_at desc);
create index documents_status_idx on public.documents (generation_status);
create index documents_number_idx on public.documents (document_number, revision desc);

comment on column public.documents.storage_path is
  'Immutable object path inside the private generated-pdfs bucket. Never overwritten: a regeneration creates a new revision.';

-- ---------------------------------------------------------------------------
-- document_items — the exact asset set inside a register export
-- ---------------------------------------------------------------------------
create table public.document_items (
  document_id uuid    not null references public.documents (id) on delete cascade,
  asset_id    uuid    not null references public.assets (id) on delete restrict,
  row_order   integer not null,
  primary key (document_id, asset_id),
  constraint document_items_row_order_positive check (row_order > 0)
);

create index document_items_asset_id_idx on public.document_items (asset_id);

-- ---------------------------------------------------------------------------
-- Document numbering
-- A single global sequence makes numbers race-free without application retries.
-- Only the server (secret key) may call this.
-- ---------------------------------------------------------------------------
create sequence public.document_number_seq start 1;

create or replace function public.next_document_number(
  p_document_type text,
  p_asset_id uuid default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_seq       text;
  v_type_code text;
  v_at        timestamptz := now();
begin
  v_seq := lpad(nextval('public.document_number_seq')::text, 4, '0');

  if p_document_type = 'asset' then
    select t.code
      into v_type_code
      from public.assets a
      join public.asset_types t on t.id = a.asset_type_id
     where a.id = p_asset_id;

    if v_type_code is null then
      raise exception 'asset % not found for document numbering', p_asset_id
        using errcode = 'P0002';
    end if;

    return format('ITA-%s-%s-%s', v_type_code, to_char(v_at, 'YYMM'), v_seq);
  elsif p_document_type = 'register' then
    return format('REG-%s-%s', to_char(v_at, 'YYMMDD'), v_seq);
  end if;

  raise exception 'unknown document type: %', p_document_type using errcode = '22023';
end;
$$;

revoke all on function public.next_document_number(text, uuid) from public, anon, authenticated;
grant execute on function public.next_document_number(text, uuid) to service_role;
